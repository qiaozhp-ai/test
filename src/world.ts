// 房间在世界里的排布（行 = 从上到下）
const LAYOUT = [
  ["C", "D"],
  ["A", "B"],
];

export interface Entity {
  kind: "spawn" | "lantern" | "egg";
  id: string;
  x: number; // 世界像素坐标（瓦片左上角）
  y: number;
}

export interface World {
  cols: number;
  rows: number;
  solid: Uint8Array; // 1 = 岩石
  entities: Entity[];
  roomsX: number;
  roomsY: number;
  roomName(rx: number, ry: number): string | undefined;
  isSolid(tx: number, ty: number): boolean;
}

export function buildWorld(rooms = ROOMS, layout = LAYOUT): World {
  const roomsY = layout.length;
  const roomsX = layout[0].length;
  const cols = roomsX * ROOM_W;
  const rows = roomsY * ROOM_H;
  // 没有房间的格子当作实心岩石
  const solid = new Uint8Array(cols * rows).fill(1);
  const entities: Entity[] = [];

  layout.forEach((line, ry) =>
    line.forEach((name, rx) => {
      const data = rooms[name];
      if (!data) return;
      data.forEach((row, y) => {
        [...row].forEach((ch, x) => {
          const tx = rx * ROOM_W + x;
          const ty = ry * ROOM_H + y;
          solid[ty * cols + tx] = ch === "#" ? 1 : 0;
          const id = `${name}:${x},${y}`;
          if (ch === "P") entities.push({ kind: "spawn", id, x: tx * TILE, y: ty * TILE });
          if (ch === "L") entities.push({ kind: "lantern", id, x: tx * TILE, y: ty * TILE });
          if (ch === "*") entities.push({ kind: "egg", id, x: tx * TILE, y: ty * TILE });
        });
      });
    }),
  );

  return {
    cols,
    rows,
    solid,
    entities,
    roomsX,
    roomsY,
    roomName: (rx, ry) => layout[ry]?.[rx],
    // 世界外面也算实心，防止掉出地图
    isSolid: (tx, ty) => tx < 0 || ty < 0 || tx >= cols || ty >= rows || solid[ty * cols + tx] === 1,
  };
}

